export const FAQ_LIBRARY: FAQEntry[] = [...faqEntries, ...extraFaqs].slice(0, 500);

export const findFAQAnswer = (query: string): FAQEntry | null => {
  const text = query.toLowerCase();
  const tokens = text.split(/[^a-z0-9]+/).filter(Boolean);
  const categoryAliases: Record<string, string[]> = {
    LeadLock: ['lead lock', 'lead theft', 'lead poach'],
    DealLock: ['deal lock', 'escrow', 'deal milestone'],
    Verification: ['verification', 'verify', 'title check', 'ownership check'],
    Payments: ['payment', 'jazzcash', 'easypaisa', 'invoice', 'refund'],
    Subscriptions: ['subscription', 'billing plan', 'premium plan'],
    Marketplace: ['marketplace', 'property portal', 'national inventory'],
    VoiceAI: ['voice ai', 'voice assistant', 'speech'],
    CRM: ['crm', 'follow up', 'follow-up', 'appointment', 'contact'],
  };

  let bestMatch: FAQEntry | null = null;
  let bestScore = 0;

  for (const faq of FAQ_LIBRARY) {
    const combined = `${faq.question} ${faq.category} ${faq.keywords.join(' ')}`.toLowerCase();
    let score = 0;
    for (const token of tokens) {
      if (combined.includes(token)) score += 2;
    }
    if (categoryAliases[faq.category]?.some((alias) => text.includes(alias))) score += 20;
    if (faq.category.toLowerCase() === text) score += 5;
    if (score > bestScore) {
      bestScore = score;
      bestMatch = faq;
    }
  }

  return bestScore > 0 ? bestMatch : FAQ_LIBRARY[0] ?? null;
};
